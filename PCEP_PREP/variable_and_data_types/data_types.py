#Numerical representations:
#Integer: Whole numbers without a decimal point.
#Float: Numbers with a decimal point.
#scientific notation: A way to represent very large or very small numbers using powers of 10. For example, 1.5e3 represents 1.5 x 10^3, which is equal to 1500.

number = 1.5e3 #scientific notation

#octal numbers: Base-8 number system, using digits 0-7. In Python, octal numbers are represented with a leading '0o' or '0O'. For example, 0o10 represents the octal number 10, which is equal to 8 in decimal.
octal_number = 0o10 #octal number

#hexadecimal numbers: Base-16 number system, using digits 0-9 and letters A-F (or a-f) to represent values 10-15. In Python, hexadecimal numbers are represented with a leading '0x' or '0X'. For example, 0x1A represents the hexadecimal number 1A, which is equal to 26 in decimal.
hexadecimal_number = 0x1A #hexadecimal number